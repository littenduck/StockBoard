"""Build static/icons.svg from the official Tabler Icons package in node_modules.

Every icon's paths are copied unchanged from node_modules/@tabler/icons. The only
change is the stroke width of outline icons, set so they render at 1.5px in a 16px box.
Run after `npm install`: .venv/bin/python scripts/build_icons.py
"""
import os
import re
import shutil

PROJECT_DIRECTORY = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TABLER_DIRECTORY = os.path.join(PROJECT_DIRECTORY, "node_modules", "@tabler", "icons")
OUTPUT_SPRITE_PATH = os.path.join(PROJECT_DIRECTORY, "static", "icons.svg")
OUTPUT_FAVICON_PATH = os.path.join(PROJECT_DIRECTORY, "static", "favicon.svg")
LICENSE_OUTPUT_PATH = os.path.join(PROJECT_DIRECTORY, "licenses", "tabler-icons-LICENSE.txt")
ACCENT_COLOR = "#C96442"
# 1.5px rendered in a 16px box means 1.5 * 24 / 16 = 2.25 units in Tabler's 24-unit viewBox.
OUTLINE_STROKE_WIDTH = "2.25"

# symbol id used by the pages -> (style, Tabler icon name)
ICON_SOURCE_BY_SYMBOL_ID = {
    "icon-pass": ("filled", "circle-check"),
    "icon-fail": ("filled", "circle-x"),
    "icon-unknown": ("outline", "help-circle"),
    "icon-not-applicable": ("outline", "minus"),
    "icon-help": ("outline", "info-circle"),
    "icon-close": ("outline", "x"),
    "icon-theme": ("outline", "circle-half-2"),
    "icon-language": ("outline", "language"),
    "icon-chevron": ("outline", "chevron-down"),
}
FAVICON_SOURCE = ("outline", "chart-line")


def build_icons_read_tabler_svg_inner_markup(style: str, icon_name: str) -> str:
    """Return the inner markup (paths) of one Tabler icon, exactly as published."""
    path = os.path.join(TABLER_DIRECTORY, "icons", style, icon_name + ".svg")
    with open(path) as icon_file:
        svg_text = icon_file.read()
    inner_match = re.search(r">(.*)</svg>", svg_text, re.DOTALL)
    if not inner_match:
        raise ValueError("unexpected Tabler SVG layout: " + path)
    return inner_match.group(1).strip()


def build_icons_make_symbol(symbol_id: str, style: str, icon_name: str) -> str:
    inner_markup = build_icons_read_tabler_svg_inner_markup(style, icon_name)
    if style == "filled":
        attributes = 'fill="currentColor"'
    else:
        attributes = (f'fill="none" stroke="currentColor" stroke-width="{OUTLINE_STROKE_WIDTH}" '
                      'stroke-linecap="round" stroke-linejoin="round"')
    return f'<symbol id="{symbol_id}" viewBox="0 0 24 24" {attributes}>{inner_markup}</symbol>'


def build_icons_write_sprite() -> None:
    lines = [
        '<svg xmlns="http://www.w3.org/2000/svg" style="display:none">',
        "<!-- Icons: Tabler Icons 3.49.0, MIT License, https://tabler.io/icons. Paths copied unchanged; "
        "outline stroke width adjusted. Full license: licenses/tabler-icons-LICENSE.txt. Generated by scripts/build_icons.py -->",
    ]
    for symbol_id, (style, icon_name) in ICON_SOURCE_BY_SYMBOL_ID.items():
        lines.append(build_icons_make_symbol(symbol_id, style, icon_name))
    lines.append("</svg>")
    with open(OUTPUT_SPRITE_PATH, "w") as sprite_file:
        sprite_file.write("\n".join(lines) + "\n")


def build_icons_write_favicon() -> None:
    style, icon_name = FAVICON_SOURCE
    inner_markup = build_icons_read_tabler_svg_inner_markup(style, icon_name)
    favicon = (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="none" stroke="{ACCENT_COLOR}" '
               'stroke-width="2" stroke-linecap="round" stroke-linejoin="round">' + inner_markup + "</svg>\n")
    with open(OUTPUT_FAVICON_PATH, "w") as favicon_file:
        favicon_file.write(favicon)


def build_icons_copy_license() -> None:
    os.makedirs(os.path.dirname(LICENSE_OUTPUT_PATH), exist_ok=True)
    shutil.copyfile(os.path.join(TABLER_DIRECTORY, "LICENSE"), LICENSE_OUTPUT_PATH)


if __name__ == "__main__":
    build_icons_write_sprite()
    build_icons_write_favicon()
    build_icons_copy_license()
    print("wrote", OUTPUT_SPRITE_PATH, OUTPUT_FAVICON_PATH, LICENSE_OUTPUT_PATH)
